//User table created

CREATE TABLE USERS (
    USER_ID NUMBER PRIMARY KEY,
    FULL_NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(150) UNIQUE NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    ROLE VARCHAR2(20) DEFAULT 'STUDENT' NOT NULL,
    MUST_CHANGE_PASSWORD NUMBER(1) DEFAULT 0 NOT NULL,
    PASSWORD_EXPIRES_AT TIMESTAMP NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    IS_ACTIVE NUMBER(1) DEFAULT 1,
    CONSTRAINT CK_USERS_ROLE CHECK (ROLE IN ('ADMIN', 'TRAINER', 'STUDENT')),
    CONSTRAINT CK_USERS_MUST_CHANGE CHECK (MUST_CHANGE_PASSWORD IN (0, 1))
);

//Sequence Created

create sequence user_seq 
start with 1
increment by 1
nocache;

//Password_reset_token Table Created

CREATE TABLE PASSWORD_RESET_TOKEN (
    TOKEN_ID NUMBER PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    RESET_TOKEN VARCHAR2(255) UNIQUE NOT NULL,
    EXPIRY_TIME TIMESTAMP NOT NULL,
    USED NUMBER(1) DEFAULT 0,

    CONSTRAINT FK_RESET_USER
        FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID)
);

CREATE SEQUENCE RESET_TOKEN_SEQ
START WITH 1
INCREMENT BY 1
NOCACHE;

