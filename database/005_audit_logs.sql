
-- 1. Create the audit log table

CREATE TABLE AUDIT_LOG (
    LOG_ID          NUMBER(19)      NOT NULL,
    ACTOR_USER_ID   NUMBER(19),
    ACTOR_NAME      VARCHAR2(100),
    ACTOR_EMAIL     VARCHAR2(150),
    ACTOR_ROLE      VARCHAR2(30),

    ACTION          VARCHAR2(50)    NOT NULL,
    ENTITY_TYPE     VARCHAR2(50)    NOT NULL,
    ENTITY_ID       NUMBER(19),

    DESCRIPTION     VARCHAR2(1000),
    OLD_VALUE       CLOB,
    NEW_VALUE       CLOB,

    IP_ADDRESS      VARCHAR2(64),
    REQUEST_METHOD  VARCHAR2(10),
    REQUEST_PATH    VARCHAR2(500),

    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_AUDIT_LOG PRIMARY KEY (LOG_ID)
);

-- 2. Create a sequence for unique audit log IDs

CREATE SEQUENCE AUDIT_LOG_SEQ
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

-- 3. Index the columns used for filtering and sorting

CREATE INDEX IDX_AUDIT_LOG_CREATED
    ON AUDIT_LOG (CREATED_AT);

CREATE INDEX IDX_AUDIT_LOG_ACTOR
    ON AUDIT_LOG (ACTOR_USER_ID, CREATED_AT);

CREATE INDEX IDX_AUDIT_LOG_ACTION
    ON AUDIT_LOG (ACTION, CREATED_AT);

CREATE INDEX IDX_AUDIT_LOG_ENTITY
    ON AUDIT_LOG (ENTITY_TYPE, ENTITY_ID);

